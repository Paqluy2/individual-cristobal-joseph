package com.joysistvi.day3.variable;

public class Activity1_Cristobal {

    public static void main(String[] args) {

        boolean is_rising = false;
        is_rising = true;
        System.out.println("boolean: " + is_rising);

        byte activityNum = 1;
        System.out.println("byte: " +  activityNum);

        short zipCode = 1860;
        System.out.println("short: " + zipCode);

        int year = 2026;
        System.out.println("int: " + year);

        long price = 125000000L;
        System.out.println("long: " + price);

        float finalGrade = 3.00f;
        System.out.println("float: " + finalGrade);

        double accountBalance = 10.123123123d;
        System.out.println("double: " + accountBalance);

        char grade = 'F';
        System.out.println("char: " + grade);

        String productName = "Banana Chips";
        System.out.println("String: " + productName);

    }
}
